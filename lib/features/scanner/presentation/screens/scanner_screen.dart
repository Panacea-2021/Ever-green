            topRight: Radius.circular(24),
          ),
        ),
        child: ForeignEquipmentNotice(
          actionLabel: 'Scan Again',
          onAction: () => Navigator.pop(sheetContext),
        ),
      ),
    ).whenComplete(_resetScanner);
  }

