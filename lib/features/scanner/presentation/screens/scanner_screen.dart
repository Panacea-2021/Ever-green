/// Scans an equipment QR sticker (the bare equipment id, as generated by the
/// backend), marks the equipment verified (`verifyEquipment`) and opens its
/// details.
class ScannerScreen extends ConsumerStatefulWidget {
  const ScannerScreen({super.key});

  @override
  ConsumerState<ScannerScreen> createState() => _ScannerScreenState();
}

class _ScannerScreenState extends ConsumerState<ScannerScreen>
    with SingleTickerProviderStateMixin, WidgetsBindingObserver {
  final MobileScannerController _controller = MobileScannerController(
    formats: const [BarcodeFormat.qrCode],
    detectionSpeed: DetectionSpeed.noDuplicates,
  );
  bool _isScanned = false;
  bool _flashOn = false;
  bool _lookingUp = false;
  late AnimationController _animationController;
  late Animation<double> _animation;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    _animationController = AnimationController(
      duration: const Duration(seconds: 2),
      vsync: this,
    )..repeat(reverse: true);

    _animation = Tween<double>(begin: 0, end: 1).animate(
      CurvedAnimation(
        parent: _animationController,
        curve: Curves.easeInOut,
      ),
    );
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (!_controller.value.hasCameraPermission) return;
    switch (state) {
      case AppLifecycleState.resumed:
        if (!_isScanned) _controller.start();
      case AppLifecycleState.inactive:
      case AppLifecycleState.paused:
        _controller.stop();
      default:
        break;
    }
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _animationController.dispose();
    _controller.dispose();
    super.dispose();
  }

  void _onDetect(BarcodeCapture capture) {
    for (final barcode in capture.barcodes) {
      final raw = barcode.rawValue;
      if (raw != null && raw.trim().isNotEmpty) {
        _onCodeScanned(raw);
        return;
      }
    }
  }

  Future<void> _onCodeScanned(String raw) async {
    if (_isScanned) return;
    final code = parseEquipmentCode(raw);

    setState(() {
      _isScanned = true;
      _lookingUp = code != null;
    });

    HapticFeedback.mediumImpact();
    await _controller.stop();

    if (code == null) {
      _snack('This QR code is not an EverGreen equipment code');
      _resetScanner();
      return;
    }

    final Equipment equipment;
    try {
      equipment = (await ref
              .read(equipmentApiProvider)
              .getInfo(code, user: ref.read(currentUserProvider)))
          .equipment;
    } on ForeignEquipmentException {
      if (!mounted) return;
      setState(() => _lookingUp = false);
      _showForeignEquipmentSheet();
      return;
    } catch (e) {
      _snack('$e');
      _resetScanner();
      return;
    }
    try {
      await ref.read(equipmentApiProvider).verify(equipment.id);
      ref.invalidate(verifiedEquipmentsProvider);
      ref.invalidate(equipmentInfoProvider);
    } catch (e) {
      _snack('Could not verify the equipment: $e');
    }
    if (!mounted) return;
    setState(() => _lookingUp = false);
    _showResultBottomSheet(equipment);
  }

  void _resetScanner() {
    if (!mounted) return;
    setState(() {
      _isScanned = false;
      _lookingUp = false;
    });
    _controller.start();
  }

  Future<void> _toggleFlash() async {
    try {
      await _controller.toggleTorch();
      if (mounted) setState(() => _flashOn = !_flashOn);
    } catch (_) {
      _snack('Flash is not available');
    }
  }

  Future<void> _pickFromPhotos() async {
    if (_isScanned) return;
    final XFile? file;
    try {
      file = await ImagePicker().pickImage(source: ImageSource.gallery);
    } catch (e) {
      _snack('Could not open photos: $e');
      return;
    }
    if (file == null || !mounted) return;
    try {
      final capture = await _controller.analyzeImage(
        file.path,
        formats: const [BarcodeFormat.qrCode],
      );
      final raw = capture?.barcodes
          .map((b) => b.rawValue)
          .whereType<String>()
          .where((v) => v.trim().isNotEmpty)
          .firstOrNull;
      if (raw == null) {
        _snack('No QR code found in that photo');
        return;
      }
      await _onCodeScanned(raw);
    } catch (e) {
      _snack('Could not read that photo: $e');
    }
  }

  Future<void> _enterManually() async {
    if (_isScanned) return;
    final textController = TextEditingController();
    final value = await showDialog<String>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text(
          'Find equipment',
          style:
              TextStyle(fontFamily: 'Montserrat', fontWeight: FontWeight.w600),
        ),
        content: TextField(
          controller: textController,
          autofocus: true,
          textInputAction: TextInputAction.search,
          onSubmitted: (v) => Navigator.pop(ctx, v),
          decoration: const InputDecoration(
            hintText: 'Equipment ID or serial number',
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: const Text('Cancel'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(ctx, textController.text),
            child: const Text(
              'Search',
              style: TextStyle(color: Color(0xFF106220)),
            ),
          ),
        ],
      ),
    );
    textController.dispose();
    if (value == null || value.trim().isEmpty || !mounted) return;
    await _onCodeScanned(value.trim());
  }

  void _snack(String message) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text(message), behavior: SnackBarBehavior.floating),
    );
  }

  void _openDetails(Equipment e) {
    context.pushReplacement(
      '${Routes.equipmentDetails}/${e.id}',
      extra: {
        'equipmentName': e.name,
        'location': e.location,
        'imageUrl': e.imageUrl,
        'make': e.make,
        'model': e.model,
        'serialNumber': e.serialNumber,
        'companyId': e.companyId?.toString(),
        'companyName': e.company?.displayName,
      },
    );
  }

  void _showResultBottomSheet(Equipment equipment) {
    var leaving = false;
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (sheetContext) => _ScanResultBottomSheet(
        code: equipment.egSerialNumber.isNotEmpty
            ? equipment.egSerialNumber
            : '${equipment.id}',
        onScanAgain: () => Navigator.pop(sheetContext),
        onViewDetails: () {
          leaving = true;
          Navigator.pop(sheetContext);
          _openDetails(equipment);
        },
      ),
    ).whenComplete(() {
      if (!leaving) _resetScanner();
    });
  }

  void _showForeignEquipmentSheet() {
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      builder: (sheetContext) => Container(
        padding: const EdgeInsets.fromLTRB(24, 24, 24, 40),
