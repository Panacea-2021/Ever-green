  Widget _buildScannerFrame(Size size) {
    final frameSize = size.width * 0.75;

    return SizedBox(
      width: frameSize,
      height: frameSize,
      child: Stack(
        children: [
          // Live camera preview inside the frame
          Positioned.fill(
            child: Padding(
              padding: const EdgeInsets.all(6),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(10),
                child: MobileScanner(
                  controller: _controller,
                  onDetect: _onDetect,
                  errorBuilder: (context, error) => _cameraError(error),
                ),
              ),
            ),
          ),

          // Scanner frame with corners
          CustomPaint(
            size: Size(frameSize, frameSize),
            painter: _ScannerFramePainter(),
          ),

          if (_lookingUp)
            const Positioned.fill(
              child: Center(
                child: CircularProgressIndicator(color: Color(0xFF5B7FFF)),
              ),
            ),

          // Scanning line animation
          if (!_isScanned)
            AnimatedBuilder(
              animation: _animation,
              builder: (context, child) {
                return Positioned(
                  top: 20 + (_animation.value * (frameSize - 40)),
                  left: 20,
                  right: 20,
                  child: Container(
                    height: 3,
                    decoration: BoxDecoration(
                      gradient: LinearGradient(
                        colors: [
                          Colors.transparent,
                          const Color(0xFF2196F3).withValues(alpha: 0.6),
                          const Color(0xFF2196F3),
                          const Color(0xFF2196F3).withValues(alpha: 0.6),
                          Colors.transparent,
                        ],
                      ),
                      boxShadow: [
                        BoxShadow(
                          color: const Color(0xFF2196F3).withValues(alpha: 0.4),
                          blurRadius: 8,
                          spreadRadius: 1,
                        ),
                      ],
                    ),
                  ),
                );
              },
            ),
        ],
      ),
    );
  }

  Widget _cameraError(MobileScannerException error) {
    final denied = error.errorCode == MobileScannerErrorCode.permissionDenied;
    return Container(
      color: const Color(0xFFF5F5F5),
      padding: const EdgeInsets.all(16),
      alignment: Alignment.center,
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(
            Icons.no_photography_outlined,
            color: Colors.grey[500],
            size: 36,
          ),
          const SizedBox(height: 10),
          Text(
            denied
                ? 'Allow camera access in Settings to scan'
                : 'Camera unavailable',
            textAlign: TextAlign.center,
            style: TextStyle(
              fontFamily: 'Montserrat',
              fontSize: 12,
              color: Colors.grey[600],
